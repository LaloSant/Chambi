CREATE TABLE PROFESSIONS (
	PROF_ID SERIAL PRIMARY KEY,
	NAME VARCHAR(50)
);

CREATE TABLE LOCATIONS (
	LOCATION_ID SERIAL PRIMARY KEY,
	USER_ID INT REFERENCES USERS(USER_ID),
	NAME VARCHAR(100),
	LATITUDE DECIMAL,
	LONGITUDE DECIMAL,
	TYPE VARCHAR(20),
	STREETLINE VARCHAR(20),
	CITY VARCHAR(20),
	STATE VARCHAR(20),
	POSTAL_CODE VARCHAR(5),
	CONSTRAINT LOCATIONS_TYPE_CK CHECK (TYPE IN ('HOUSE', 'APARTMENT', 'OFFICE', 'OTHERS'))
);

CREATE TABLE USERS (
	USER_ID SERIAL PRIMARY KEY,
	EMAIL VARCHAR(255) NOT NULL UNIQUE,
	NAME VARCHAR(100) NOT NULL,
	PASSWORD VARCHAR(255) NOT NULL,
	PHONE_NUMBER VARCHAR(10) NOT NULL,
	PHOTO BYTEA
);

CREATE TABLE PROFESSIONS_USERS (
	PROF_USR_ID SERIAL PRIMARY KEY,
	PROF_ID INT REFERENCES PROFESSIONS (PROF_ID),
	USER_ID INT REFERENCES USERS (USER_ID)
);

