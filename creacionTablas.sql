CREATE TABLE JOB_TYPE (
	JOB_TYPE_ID SERIAL PRIMARY KEY,
	NAME VARCHAR(50) NOT NULL,
	DESCRIPTION VARCHAR(150) NOT NULL
);

CREATE TABLE QUESTIONS (
	QUESTION_ID SERIAL PRIMARY KEY,
	TEXT VARCHAR(150) NOT NULL,
	DATA_TYPE VARCHAR(10) NOT NULL
);

CREATE TABLE JOBS (
	JOB_ID SERIAL PRIMARY KEY,
	CONTRACTOR_ID INT,
	WORKER_ID INT,
	JOB_TYPE_ID INT NOT NULL,
	STATUS VARCHAR(25) NOT NULL,
	NAME VARCHAR(100),
	DESCRIPTION VARCHAR(255),
	COST DECIMAL,
	COST_TYPE VARCHAR(5),
	RATING INT,
	PHOTO BYTEA,
	FOREIGN KEY (CONTRACTOR_ID) REFERENCES users (user_id ),
	FOREIGN KEY (WORKER_ID) REFERENCES users (user_id),
	FOREIGN KEY (JOB_TYPE_ID) REFERENCES job_type (JOB_TYPE_ID),
	CONSTRAINT JOBS_STATUS_CK CHECK (STATUS IN ('PENDING', 'SOLVED', 'CANCELED', 'WORK_NOT_ASSIGNED', 'CONT_NOT_ASSIGNED')),
	CONSTRAINT JOBS_COSTTYPE_CK CHECK (COST_TYPE IN ('/HOUR', 'TOTAL')),
	CONSTRAINT JOBS_RATING_CK CHECK (RATING <= 5)
);

CREATE TABLE DETAILS (
	DETAILS_ID SERIAL PRIMARY KEY,
	JOB_ID INT NOT NULL,
	QUESTION_ID INT NOT NULL,
	VALUE VARCHAR(100) NOT NULL,
	FOREIGN KEY (JOB_ID) REFERENCES JOBS (JOB_ID),
	FOREIGN KEY (QUESTION_ID) REFERENCES QUESTIONS (QUESTION_ID)
);

